async function handleResponseError(res: Response, defaultMessage: string): Promise<never> {
  let detailMessage = defaultMessage;
  try {
    const data = await res.json();
    if (data?.detail) {
      detailMessage = typeof data.detail === "string" ? data.detail : JSON.stringify(data.detail);
    } else if (data?.error?.message) {
      detailMessage = data.error.message;
    }
  } catch {
    // Keep default message if response body is not JSON
  }
  throw new Error(detailMessage);
}

export async function fetchHealth(): Promise<boolean> {
  try {
    const res = await fetch(`${API_BASE}/health`);
    return res.ok;
  } catch {
    return false;
  }
}

export async function createProject(
  name: string,
  description?: string,
  aoiName?: string
): Promise<Project> {
  const res = await fetch(`${API_BASE}/projects`, {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify({
      name,
      description,
      aoi_name: aoiName,
    }),
  });

  if (!res.ok) {
    await handleResponseError(res, "Failed to create project");
  }

  return res.json();
}

export async function getProjects(): Promise<Project[]> {
  const res = await fetch(`${API_BASE}/projects`);
  if (!res.ok) await handleResponseError(res, "Failed to fetch projects");
  return res.json();
}
export async function resetProject(projectId: string): Promise<Project> {
  const res = await fetch(
    `${API_BASE}/projects/${projectId}/reset`,
    {
      method: "POST",
    }
  );

  if (!res.ok) {
    await handleResponseError(
      res,
      "Failed to reset project session"
    );
  }

  return res.json();
}
export async function validateDatasets(
  projectId: string,
  analysisMode?: "vegetation" | "wetland"
): Promise<ValidationResult> {
  const url = analysisMode
    ? `${API_BASE}/projects/${projectId}/datasets/validate?analysis_mode=${analysisMode}`
    : `${API_BASE}/projects/${projectId}/datasets/validate`;
  const res = await fetch(url, {
    method: "POST",
  });
  if (!res.ok) await handleResponseError(res, "Failed to validate datasets");
  return res.json();
}

export async function uploadBandFile(
  projectId: string,
  timePoint: "t1" | "t2",
  band: "green" | "red" | "rededge" | "nir" | "boundary",
  file: File
): Promise<{ message: string; path: string }> {
  const formData = new FormData();
  formData.append("time_point", timePoint);
  formData.append("band", band);
  formData.append("file", file);

  const res = await fetch(`${API_BASE}/projects/${projectId}/datasets/upload`, {
    method: "POST",
    body: formData,
  });
  if (!res.ok) await handleResponseError(res, `Failed to upload ${band} band`);
  return res.json();
}

export async function updateProjectDates(
  projectId: string,
  t1Date: string,
  t2Date: string,
) {
  const response = await fetch(
    `${API_BASE}/projects/${projectId}/dates`,
    {
      method: "PATCH",
      headers: {
        "Content-Type": "application/json",
      },
      body: JSON.stringify({
        t1_date: t1Date,
        t2_date: t2Date,
      }),
    },
  );

  if (!response.ok) {
    const detail = await response.text();
    throw new Error(detail || "Failed to update observation dates");
  }

  return response.json();
}

export async function launchRun(projectId: string, config?: Record<string, unknown>): Promise<RunStatus> {
  const res = await fetch(`${API_BASE}/runs`, {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify({ project_id: projectId, config }),
  });
  if (!res.ok) await handleResponseError(res, "Failed to launch analysis run");
  return res.json();
}

function projectRunUrl(
  runId: string,
  projectId: string,
  suffix = ""
): string {
  if (!runId || !projectId) {
    throw new Error("Run and project identity are required.");
  }

  const query = new URLSearchParams({
    project_id: projectId,
  });

  return `${API_BASE}/runs/${encodeURIComponent(runId)}${suffix}?${query}`;
}

export async function getRunStatus(
  runId: string,
  projectId: string
): Promise<RunStatus> {
  const res = await fetch(projectRunUrl(runId, projectId));

  if (!res.ok) {
    await handleResponseError(res, "Failed to fetch run status");
  }

  const data: RunStatus = await res.json();

  if (
    data.run_id !== runId ||
    data.project_id !== projectId
  ) {
    throw new Error("Unexpected run or project identity.");
  }

  return data;
}

export async function getRunResults(
  runId: string,
  projectId: string
): Promise<AnalysisResults> {
  const res = await fetch(
    projectRunUrl(runId, projectId, "/results")
  );

  if (!res.ok) {
    await handleResponseError(res, "Failed to fetch analysis results");
  }

  const data: AnalysisResults = await res.json();

  if (data.run_id !== runId) {
    throw new Error("Unexpected analysis result identity.");
  }

  return data;
}

